#!/usr/bin/env python3
"""Burrow Breaker's art, from the concept at art/game/burrow_breaker_concept.png.

    python3 tools/make_game_art.py      # -> src/bricks_art.h, src/bricks_art.cpp

The concept is a T-Deck screen (320 x 240) drawn 4.525 times over, so a box filter brings it
back to the screen's own pixels. From that:
  - the background: the frame, the title bar (the hooded rabbit, the title, "SCORE"), the
    circuit lines and the city, with everything that moves taken out (blocks, packet, sparks,
    carrot, board, the score's digits, the lives). Stored run-length, unpacked once on the T-Deck;
  - the blocks: cyan, purple and amber server racks, and the steel plate whole and cracked;
  - the board with its ears, the carrot, a pair of ears for a life;
  - the colours the game draws with (the score's cyan, the sparks' magenta, and so on).
All in byte-swapped RGB565, as LovyanGFX pushes them; KEY marks a sprite's see-through pixels.
Needs Python 3 and Pillow.
"""
import os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
SRC = os.path.join(ROOT, "art", "game", "burrow_breaker_concept.png")
W, H = 320, 240
KEY = 0xF81F            # pure magenta: not in the art (checked below)

im = Image.open(SRC).convert("RGB").resize((W, H), Image.BOX)
px = im.load()
BG = (8, 1, 21)          # the play area's colour


def diff(a, b):
    return max(abs(a[i] - b[i]) for i in range(3))


def c565(c):
    r, g, b = c
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def swap(v):
    return ((v & 0xFF) << 8) | (v >> 8)


# ---- the sprites, taken before the background is cleaned ----------------------------------------
def opaque(box):
    x0, y0, x1, y1 = box
    return [[c565(px[x, y]) for x in range(x0, x1)] for y in range(y0, y1)]


def keyed(box, under, thr=12):
    """Pixels that differ from what they're drawn over; the rest see-through."""
    x0, y0, x1, y1 = box
    return [[c565(px[x, y]) if diff(px[x, y], under(x, y)) > thr else KEY for x in range(x0, x1)] for y in range(y0, y1)]


BRICK_W, BRICK_H = 36, 12
bricks = {
    "CYAN": opaque((12, 34, 48, 46)),
    "PURPLE": opaque((50, 34, 86, 46)),
    "AMBER": opaque((88, 34, 124, 46)),
    "STEEL": opaque((125, 34, 161, 46)),
    "STEEL_CRACKED": opaque((199, 48, 235, 60)),
}
board = keyed((134, 196, 186, 220), lambda x, y: BG)
carrot = keyed((106, 100, 121, 122), lambda x, y: BG)
# a life: the first pair of ears in the title bar, over the bar's own colour at that spot
bar_at = {y: px[260, y] for y in range(H)}
ears = keyed((275, 4, 292, 18), lambda x, y: bar_at[y], thr=25)

# colours sampled from the art
CYAN = max((px[x, y] for x in range(216, 258) for y in range(6, 15)), key=lambda c: c[1] + c[2])
MAGENTA = max((px[x, y] for x in range(195, 232) for y in range(56, 82)), key=lambda c: c[0] - c[1])
TRAIL = px[214, 82] if diff(px[214, 82], BG) > 20 else (40, 150, 170)
CARROT_DOT = max((px[x, y] for x in range(108, 118) for y in range(86, 100)), key=lambda c: c[0])

# ---- the background ----------------------------------------------------------------------------
bg = [[px[x, y] for x in range(W)] for y in range(H)]


def fill(x0, y0, x1, y1, c):
    for y in range(y0, y1):
        for x in range(x0, x1):
            bg[y][x] = c


# the play area: flat, so a cleared spot is the colour around it (the walls' circuit lines,
# the city and the ground stay)
for y in range(31, 223):
    for x in range(11, 310):
        if diff(bg[y][x], BG) <= 6:
            bg[y][x] = BG
fill(11, 33, 310, 90, BG)        # the blocks, the packet and its sparks
fill(185, 80, 240, 100, BG)      # the end of the packet's trail
fill(100, 84, 126, 124, BG)      # the carrot and its trail
fill(130, 195, 190, 222, BG)     # the board
# the score's digits and the lives: the title bar's own colour, row by row
for y in range(3, 19):
    c = bg[y][261]
    for x in range(216, 260):
        bg[y][x] = c
    for x in range(268, 312):
        bg[y][x] = c

flat = [swap(c565(c)) for row in bg for c in row]
assert all(v != swap(KEY) for v in flat), "the key colour is in the art"
runs = []
for v in flat:
    if runs and runs[-1][1] == v and runs[-1][0] < 0xFFFF:
        runs[-1][0] += 1
    else:
        runs.append([1, v])


# ---- writing ------------------------------------------------------------------------------------
def arr(name, rows, ctype="uint16_t"):
    vals = [swap(v) for row in rows for v in row]
    lines = [", ".join("0x%04X" % v for v in vals[i:i + 16]) for i in range(0, len(vals), 16)]
    return "const %s %s[] = {\n  %s\n};\n" % (ctype, name, ",\n  ".join(lines))


def rgb(c):
    return "0x%04X" % c565(c)


hdr = f"""// Burrow Breaker's art (generated by tools/make_game_art.py from
// art/game/burrow_breaker_concept.png: don't edit by hand). Byte-swapped RGB565, as LovyanGFX
// pushes it; KEY marks a sprite's see-through pixels.
#pragma once
#include <stdint.h>

namespace bricksart {{

constexpr uint16_t KEY = 0x{swap(KEY):04X};             // byte-swapped
constexpr int W = {W}, H = {H};
// The background, run-length: (count, colour) pairs, {len(runs)} runs.
extern const uint16_t BG_RUNS[];
constexpr int BG_NRUNS = {len(runs)};
constexpr int BRICK_W = {BRICK_W}, BRICK_H = {BRICK_H};
// The blocks, in the order a level names them: cyan, purple, amber, steel, steel cracked.
extern const uint16_t* const BRICK[5];
constexpr int BOARD_W = {len(board[0])}, BOARD_H = {len(board)};
constexpr int BOARD_BAR_X = 2, BOARD_BAR_Y = 12;     // where the bar the packet bounces on starts in it
extern const uint16_t BOARD[];
constexpr int CARROT_W = {len(carrot[0])}, CARROT_H = {len(carrot)};
extern const uint16_t CARROT[];
constexpr int EARS_W = {len(ears[0])}, EARS_H = {len(ears)};
extern const uint16_t EARS[];
// Colours (plain RGB565, for drawing calls).
constexpr uint16_t C_BG = {rgb(BG)}, C_CYAN = {rgb(CYAN)}, C_MAGENTA = {rgb(MAGENTA)},
                   C_TRAIL = {rgb(TRAIL)}, C_CARROT_DOT = {rgb(CARROT_DOT)};

}}  // namespace bricksart
"""
body = ['// Burrow Breaker\'s art: see bricks_art.h. Generated by tools/make_game_art.py.\n#include "bricks_art.h"\n\nnamespace bricksart {\n']
pairs = [v for r in runs for v in r]
lines = [", ".join("0x%04X" % v for v in pairs[i:i + 16]) for i in range(0, len(pairs), 16)]
body.append("const uint16_t BG_RUNS[] = {\n  %s\n};\n" % ",\n  ".join(lines))
for name, rows in bricks.items():
    body.append("static " + arr("B_" + name, rows))
body.append("const uint16_t* const BRICK[5] = {B_CYAN, B_PURPLE, B_AMBER, B_STEEL, B_STEEL_CRACKED};\n")
body.append(arr("BOARD", board))
body.append(arr("CARROT", carrot))
body.append(arr("EARS", ears))
body.append("\n}  // namespace bricksart\n")

open(os.path.join(ROOT, "src", "bricks_art.h"), "w").write(hdr)
open(os.path.join(ROOT, "src", "bricks_art.cpp"), "w").write("\n".join(body))
size = len(pairs) * 2 + sum(len(r) * len(r[0]) * 2 for r in list(bricks.values()) + [board, carrot, ears])
print(f"background: {len(runs)} runs; art: {size / 1024:.1f} KB of flash")
print("cyan", CYAN, "magenta", MAGENTA, "trail", TRAIL, "carrot dot", CARROT_DOT)
im2 = Image.new("RGB", (W, H))
im2.putdata([c for row in bg for c in row])
im2.save(os.path.join(ROOT, "art", "game", "background.png"))
