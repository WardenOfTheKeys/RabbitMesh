#!/usr/bin/env python3
"""Turns art/costumes/costumes_sheet.png (the holiday hats and the ghost, in a row, on a
transparent background) into src/costume_sprite.h: each item shrunk to the rabbit's scale and
stored as horizontal runs of one colour, drawn on the T-Deck with drawFastHLine (no image push).

    python3 tools/make_costumes.py [--sheet ...] [--out ...]

Items, left to right on the sheet: santa, pilgrim, party, witch, ghost. Each gets a target
width in pixels (WIDTHS); its anchor is the middle of its bottom edge (a hat's brim line), which
scene_holiday.h puts on the crown of his hood. Needs Pillow + numpy.
"""
import argparse
import os
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
NAMES = ["santa", "pilgrim", "party", "witch", "ghost"]
WIDTHS = {"santa": 22, "pilgrim": 21, "party": 14, "witch": 24, "ghost": 22}
MAX_COLOURS = 10


def items(a):
    """Column runs of visible pixels: one per item, left to right."""
    cols = a.any(axis=0)
    out, start = [], None
    for x, v in enumerate(list(cols) + [False]):
        if v and start is None:
            start = x
        if not v and start is not None:
            if x - start > 20:
                out.append((start, x - 1))
            start = None
    return out


def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def convert(img, width):
    a = np.array(img)[:, :, 3]
    ys, xs = np.where(a >= 128)
    img = img.crop((xs.min(), ys.min(), xs.max() + 1, ys.max() + 1))
    h = max(1, round(img.height * width / img.width))
    # premultiplied shrink, so the transparent edge doesn't bleed grey into the colours
    arr = np.array(img).astype(np.float32)
    arr[:, :, :3] *= arr[:, :, 3:4] / 255.0
    small = np.array(Image.fromarray(arr.astype(np.uint8), "RGBA").resize((width, h), Image.LANCZOS)).astype(np.float32)
    alpha = small[:, :, 3]
    keep = alpha >= 110
    rgb = np.zeros_like(small[:, :, :3])
    rgb[keep] = small[keep][:, :3] / (alpha[keep][:, None] / 255.0)
    rgb = np.clip(rgb, 0, 255).astype(np.uint8)
    # a few colours: quantise what's kept
    pix = Image.fromarray(rgb, "RGB").quantize(colors=MAX_COLOURS, method=Image.Quantize.MEDIANCUT)
    idx = np.array(pix)
    pal = pix.getpalette()[: MAX_COLOURS * 3]
    # drop lone pixels (no kept neighbour): shrink noise
    k = keep.copy()
    for y in range(h):
        for x in range(width):
            if keep[y, x]:
                n = sum(keep[yy, xx] for yy in range(max(0, y - 1), min(h, y + 2)) for xx in range(max(0, x - 1), min(width, x + 2))) - 1
                if n == 0:
                    k[y, x] = False
    runs = []
    for y in range(h):
        x = 0
        while x < width:
            if not k[y, x]:
                x += 1
                continue
            c = idx[y, x]
            x0 = x
            while x < width and k[y, x] and idx[y, x] == c:
                x += 1
            runs.append((y, x0, x - x0, int(c)))
    used = sorted({r[3] for r in runs})
    remap = {c: i for i, c in enumerate(used)}
    colours = [rgb565(pal[c * 3], pal[c * 3 + 1], pal[c * 3 + 2]) for c in used]
    runs = [(y, x, n, remap[c]) for y, x, n, c in runs]
    # the anchor: the middle of the item's width at its bottom edge (a hat's brim line)
    return width, h, width // 2, h - 1, colours, runs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sheet", default=os.path.join(HERE, "..", "art", "costumes", "costumes_sheet.png"))
    ap.add_argument("--out", default=os.path.join(HERE, "..", "src", "costume_sprite.h"))
    args = ap.parse_args()
    sheet = Image.open(args.sheet).convert("RGBA")
    a = np.array(sheet)[:, :, 3] >= 128
    found = items(a)
    if len(found) != len(NAMES):
        raise SystemExit(f"expected {len(NAMES)} items on the sheet, found {len(found)}")
    L = ["// Generated by tools/make_costumes.py from art/costumes/costumes_sheet.png: the holiday hats",
         "// and the ghost, as runs of one colour (y, x, length, colour) drawn with drawFastHLine.",
         "// Each item's anchor is the middle of its bottom edge (a hat's brim line).",
         "#pragma once", "#include <stdint.h>", "", "namespace costume {", "",
         "struct Item { uint8_t w, h, ax, ay; uint16_t nRuns; const uint16_t* pal; const uint8_t* runs; };   // a head can need more than 255 runs", ""]
    total = 0
    for name, (x0, x1) in zip(NAMES, found):
        w, h, ax, ay, pal, runs = convert(sheet.crop((x0, 0, x1 + 1, sheet.height)), WIDTHS[name])
        total += len(runs) * 4 + len(pal) * 2
        L.append(f"static const uint16_t {name.upper()}_PAL[] = {{" + ", ".join(f"0x{c:04x}" for c in pal) + "};")
        flat = ", ".join(f"{y},{x},{n},{c}" for y, x, n, c in runs)
        L.append(f"static const uint8_t {name.upper()}_RUNS[] = {{{flat}}};")
        L.append(f"static const Item {name.upper()} = {{{w}, {h}, {ax}, {ay}, {len(runs)}, {name.upper()}_PAL, {name.upper()}_RUNS}};")
        L.append("")
        print(f"{name}: {w}x{h} px, {len(pal)} colours, {len(runs)} runs, anchor {ax},{ay}")
    L.append("}  // namespace costume")
    with open(args.out, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"{args.out}: {total} bytes of costume data")


if __name__ == "__main__":
    main()
